def print_frame(frame, frame_num, total_frames):
    """Print a single frame with frame counter"""
    clear()
    print(f"\033[1;36mJARVIS Assistant - Rotating ASCII Logo\033[0m")
    print(f"\033[90mFrame {frame_num + 1}/{total_frames} - Press Ctrl+C to stop\033[0m\n")
    for line in frame:
        print(f"\033[96m{line}\033[0m")
    print(f"\n\033[90mRotating on X-axis... (simulated 3D rotation)\033[0m")

def animate(fps=8, cycles=None):
    """
    Animate the rotating logo.
    
    Args:
        fps: Frames per second
        cycles: Number of full rotation cycles (None = infinite)
    """
    frame_delay = 1.0 / fps
    frame_count = 0
    total_frames = len(frames)
    cycle_count = 0
    
    try:
        while cycles is None or cycle_count < cycles:
            frame_idx = frame_count % total_frames
            print_frame(frames[frame_idx], frame_idx, total_frames)
            
            frame_count += 1
            if frame_count % total_frames == 0:
                cycle_count += 1
            
            time.sleep(frame_delay)
    
    except KeyboardInterrupt:
        clear()
        print("\033[1;32m\nAnimation stopped. JARVIS signing off...\033[0m")
        sys.exit(0)

